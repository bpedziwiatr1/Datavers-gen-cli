using DataverseGen.Core.Generators;

namespace DataverseGen.Core.Tests.Generators;

[TestClass]
public class GeneratedFileSinkTests
{
	[TestMethod]
	public void WriteFile_WritesContentAndReturnsBytes()
	{
		string root = CreateRoot();

		try
		{
			string path = Path.Combine(root, "a.cs");

			long bytes = new GeneratedFileSink().WriteFile(path, "class A {}");

			Assert.AreEqual(new FileInfo(path).Length, bytes);
			Assert.AreEqual("class A {}", File.ReadAllText(path));
		}
		finally
		{
			Directory.Delete(root, true);
		}
	}

	[TestMethod]
	public void ClearStaleFiles_RemovesOnlyUnwrittenGeneratedFiles()
	{
		string root = CreateRoot();

		try
		{
			string written = Path.Combine(root, "written.cs");
			string stale = Path.Combine(root, "stale.cs");
			string handWritten = Path.Combine(root, "hand.cs");
			File.WriteAllText(stale, "// <auto-generated>\nclass Old {}");
			File.WriteAllText(handWritten, "class Mine {}");
			GeneratedFileSink sink = new();
			sink.WriteFile(written, "// <auto-generated>\nclass New {}");

			sink.ClearStaleFiles("*.cs", root);

			Assert.IsTrue(File.Exists(written));
			Assert.IsFalse(File.Exists(stale));
			Assert.IsTrue(File.Exists(handWritten));
		}
		finally
		{
			Directory.Delete(root, true);
		}
	}

	[TestMethod]
	public void ClearStaleFiles_ScansNestedDirectoryOnce()
	{
		string root = CreateRoot();

		try
		{
			string nested = Path.Combine(root, "customapi");
			Directory.CreateDirectory(nested);
			string stale = Path.Combine(nested, "old.cs");
			File.WriteAllText(stale, "// <auto-generated>\nclass Old {}");

			new GeneratedFileSink().ClearStaleFiles("*.cs", root, nested);

			Assert.IsFalse(File.Exists(stale));
		}
		finally
		{
			Directory.Delete(root, true);
		}
	}

	private static string CreateRoot()
	{
		string root = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString("N"));
		Directory.CreateDirectory(root);

		return root;
	}
}
